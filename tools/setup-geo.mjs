// tools/setup-geo.mjs — one-time: download Natural Earth 50m countries, simplify, write props/maps/baseMap/geo-data.js.
// Usage: npm run setup:geo
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/env.mjs';

const URLS = [
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson',
  'https://cdn.jsdelivr.net/gh/nvkelso/natural-earth-vector@master/geojson/ne_50m_admin_0_countries.geojson',
];
const TOL = 0.02, MIN_SPAN = 0.03;

function simplify(pts, tol) {
  if (pts.length < 5) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const t = len2 === 0 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2));
      const d = Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

let json = null;
for (const url of URLS) {
  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    json = await res.json();
    console.log(`✔ downloaded ${url}`);
    break;
  } catch (e) { console.log(`✖ ${url}: ${e.message}`); }
}
if (!json) { console.error('Could not download the map data. Check your connection and re-run.'); process.exit(1); }

const features = [];
for (const f of json.features) {
  const g = f.geometry;
  if (!g) continue;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  const rings = [];
  let w = 180, s = 90, e = -180, n = -90;
  for (const poly of polys) for (const ring of poly) {
    const lons = ring.map((p) => p[0]), lats = ring.map((p) => p[1]);
    if (Math.max(...lons) - Math.min(...lons) < MIN_SPAN && Math.max(...lats) - Math.min(...lats) < MIN_SPAN) continue;
    const simp = simplify(ring, TOL);
    if (simp.length < 4) continue;
    rings.push(simp.flatMap(([lo, la]) => [Math.round(lo * 100) / 100, Math.round(la * 100) / 100]));
    w = Math.min(w, ...lons); e = Math.max(e, ...lons); s = Math.min(s, ...lats); n = Math.max(n, ...lats);
  }
  if (!rings.length) continue;
  const p = f.properties ?? {};
  features.push({ n: String(p.NAME ?? p.ADMIN ?? '').toLowerCase(), a: String(p.ADMIN ?? p.NAME ?? '').toLowerCase(), b: [w, s, e, n], r: rings });
}

const out = path.join(ROOT, 'props/maps/baseMap/geo-data.js');
fs.writeFileSync(out, `// props/maps/baseMap/geo-data.js — GENERATED by tools/setup-geo.mjs from Natural Earth (public domain). Do not edit.\nexport default ${JSON.stringify({ v: 1, features })};\n`);
console.log(`✔ wrote ${path.relative(ROOT, out)} — ${features.length} features, ${(fs.statSync(out).size / 1024).toFixed(0)} KB`);
console.log(features.some((f) => f.n === 'hong kong') ? '✔ "Hong Kong" is present' : '⚠ no "Hong Kong" feature in this dataset; baseMap would need another source for it');
