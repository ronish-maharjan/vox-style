// tools/scan-props.mjs — discover props, validate shape, write registries. Usage: npm run scan
// Writes props/registry.generated.js and projects/<name>/registry.generated.js (kit + that project's local props; local overrides).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { assertPropShape } from '../core/protocol.js';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** folders containing index.js; skips names starting with _ or . ; does not descend into a prop folder */
export function findPropDirs(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!e.isDirectory() || /^[_.]/.test(e.name) || e.name === 'node_modules') continue;
    const d = path.join(dir, e.name);
    if (fs.existsSync(path.join(d, 'index.js'))) out.push(d); else out.push(...findPropDirs(d));
  }
  return out;
}

const pick = (m) => m.default || Object.values(m).find((v) => v && v.meta && typeof v.draw === 'function');

async function inspect(dirs) {
  const seen = new Map(), items = [];
  for (const d of dirs) {
    const file = path.join(d, 'index.js'), where = path.relative(ROOT, d);
    const prop = pick(await import(pathToFileURL(file).href));
    assertPropShape(prop, where);
    if (prop.meta.name !== path.basename(d)) throw new Error(`${where}: folder name must equal meta.name ("${prop.meta.name}")`);
    if (seen.has(prop.meta.name)) throw new Error(`duplicate prop "${prop.meta.name}": ${seen.get(prop.meta.name)} and ${where}`);
    seen.set(prop.meta.name, where);
    items.push({ name: prop.meta.name, dir: d });
  }
  return items;
}

function registrySource(fromDir, items) {
  const rel = (d) => { const r = path.relative(fromDir, d).split(path.sep).join('/'); return `${r.startsWith('.') ? r : './' + r}/index.js`; };
  return `// AUTO-GENERATED by tools/scan-props.mjs — do not edit. Run: npm run scan\n` +
    items.map((it, i) => `import * as m${i} from '${rel(it.dir)}';`).join('\n') +
    `\nconst pick = (m) => m.default || Object.values(m).find((v) => v && v.meta && typeof v.draw === 'function');\n` +
    `export const props = {};\nfor (const m of [${items.map((_, i) => 'm' + i).join(', ')}]) { const p = pick(m); props[p.meta.name] = p; }\n`;
}

export async function scan({ root = ROOT } = {}) {
  const kit = await inspect(findPropDirs(path.join(root, 'props')));
  fs.writeFileSync(path.join(root, 'props', 'registry.generated.js'), registrySource(path.join(root, 'props'), kit));
  const result = { kit: kit.map((k) => k.name), projects: {} };
  const pdir = path.join(root, 'projects');
  if (fs.existsSync(pdir)) {
    for (const e of fs.readdirSync(pdir, { withFileTypes: true })) {
      if (!e.isDirectory()) continue;
      const base = path.join(pdir, e.name), local = await inspect(findPropDirs(path.join(base, 'props')));
      const merged = new Map(kit.map((k) => [k.name, k]));
      for (const l of local) merged.set(l.name, l);             // project-local overrides kit
      fs.writeFileSync(path.join(base, 'registry.generated.js'), registrySource(base, [...merged.values()]));
      result.projects[e.name] = [...merged.keys()];
    }
  }
  return result;
}

export async function loadProps(project, root = ROOT) {
  return (await import(pathToFileURL(path.join(root, 'projects', project, 'registry.generated.js')).href)).props;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  scan().then((r) => {
    console.log(`kit props (${r.kit.length}): ${r.kit.join(', ') || '(none)'}`);
    for (const [p, names] of Object.entries(r.projects)) console.log(`project ${p}: ${names.length} props available`);
  }).catch((e) => { console.error('scan failed:', e.message); process.exit(1); });
}
